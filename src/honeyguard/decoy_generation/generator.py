"""
HoneyGuard Synthetic Decoy File Generator
Generates realistic PDF, DOCX, XLSX, and TXT files with synthetic, non-sensitive content.
"""

from pathlib import Path
from typing import Dict, Any
import docx
import xlsxwriter

from honeyguard.utils.logger import get_logger

logger = get_logger("HoneyGuard.Generator")


def _generate_synthetic_pdf(output_path: Path, template: Dict[str, Any]):
    """Generate a clean, valid PDF 1.4 document using native PDF formatting."""
    title = template.get("title", "CONFIDENTIAL BUSINESS REPORT")
    sections = template.get("sections", [
        ("Overview", "This document contains synthetic corporate evaluation telemetry."),
        ("Security Policy", "Access to this canary asset is monitored in real-time.")
    ])

    # Construct clean PDF text streams
    lines = [
        "BT",
        "/F1 18 Tf",
        "50 750 Td",
        f"({title[:60]}) Tj",
        "/F1 10 Tf",
        "0 -25 Td",
        "(Generated by HoneyGuard Enterprise Security Layer | Classification: Canary Token) Tj",
        "0 -30 Td"
    ]

    y_offset = -20
    for header, body in sections:
        lines.append("/F1 12 Tf")
        lines.append(f"0 {y_offset} Td")
        lines.append(f"({header}) Tj")
        lines.append("/F1 10 Tf")
        lines.append("0 -15 Td")
        # Split body into chunks
        words = body.split(" ")
        chunk = ""
        for w in words:
            if len(chunk) + len(w) + 1 < 75:
                chunk += (" " if chunk else "") + w
            else:
                lines.append(f"({chunk}) Tj")
                lines.append("0 -12 Td")
                chunk = w
        if chunk:
            lines.append(f"({chunk}) Tj")
            lines.append("0 -12 Td")
        y_offset = -15

    lines.append("ET")
    content_stream = "\n".join(lines).encode("latin-1", errors="replace")

    # Build PDF objects
    objs = []
    # 1: Catalog
    objs.append(b"1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n")
    # 2: Pages
    objs.append(b"2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n")
    # 3: Page
    objs.append(
        b"3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        b"/Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>\nendobj\n"
    )
    # 4: Contents Stream
    stream_header = f"4 0 obj\n<< /Length {len(content_stream)} >>\nstream\n".encode("ascii")
    stream_footer = b"\nendstream\nendobj\n"
    objs.append(stream_header + content_stream + stream_footer)
    # 5: Font
    objs.append(b"5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n")

    # Compute xref offsets
    header = b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n"
    offset = len(header)
    offsets = [offset]
    for obj in objs:
        offset += len(obj)
        offsets.append(offset)

    xref = [b"xref\n0 6\n0000000000 65535 f \n"]
    for off in offsets[:-1]:
        xref.append(f"{off:010d} 00000 n \n".encode("ascii"))
    xref_bytes = b"".join(xref)

    trailer = (
        f"trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n{offset}\n%%EOF\n"
    ).encode("ascii")

    with open(output_path, "wb") as f:
        f.write(header)
        for obj in objs:
            f.write(obj)
        f.write(xref_bytes)
        f.write(trailer)


def _generate_synthetic_docx(output_path: Path, template: Dict[str, Any]):
    """Generate a realistic Word document using python-docx."""
    doc = docx.Document()
    title = template.get("title", "INTERNAL CORPORATE MEMORANDUM")
    doc.add_heading(title, level=1)

    paragraphs = template.get("paragraphs", [
        "This internal document contains operational records for authorized personnel.",
        "Confidentiality Notice: The contents of this document are protected under information security policies."
    ])

    for p in paragraphs:
        doc.add_paragraph(p)

    doc.add_paragraph("\nDocument Reference: HONEYGUARD-SEC-CANARY-2026")
    doc.save(str(output_path))


def _generate_synthetic_xlsx(output_path: Path, template: Dict[str, Any]):
    """Generate a realistic spreadsheet using xlsxwriter."""
    workbook = xlsxwriter.Workbook(str(output_path))
    sheet_name = template.get("sheet_name", "Data")
    worksheet = workbook.add_worksheet(sheet_name)

    # Styles
    header_format = workbook.add_format({
        "bold": True,
        "bg_color": "#1F4E79",
        "font_color": "white",
        "border": 1,
        "align": "center"
    })
    cell_format = workbook.add_format({"border": 1})
    currency_format = workbook.add_format({"border": 1, "num_format": "$#,##0.00"})

    headers = template.get("headers", ["ID", "Description", "Value"])
    rows = template.get("rows", [
        ["REC-01", "Synthetic Ledger Item 1", 1500.0],
        ["REC-02", "Synthetic Ledger Item 2", 2300.0],
    ])

    # Write Headers
    for col_idx, header in enumerate(headers):
        worksheet.write(0, col_idx, header, header_format)
        worksheet.set_column(col_idx, col_idx, 22)

    # Write Rows
    for row_idx, row in enumerate(rows, start=1):
        for col_idx, val in enumerate(row):
            if isinstance(val, float):
                worksheet.write(row_idx, col_idx, val, currency_format)
            else:
                worksheet.write(row_idx, col_idx, val, cell_format)

    workbook.close()


def _generate_synthetic_txt(output_path: Path, template: Dict[str, Any]):
    """Generate a realistic synthetic text file."""
    content = template.get("content", "HoneyGuard Synthetic Decoy Token\nMonitoring Active.\n")
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(content)


def generate_decoy_file(output_path: Path, file_type: str, template: Dict[str, Any]) -> Path:
    """
    Generate a decoy file on disk at output_path.
    Supported types: PDF, DOCX, XLSX, TXT
    """
    p = Path(output_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    ftype = file_type.upper()

    if ftype == "PDF":
        _generate_synthetic_pdf(p, template)
    elif ftype == "DOCX":
        _generate_synthetic_docx(p, template)
    elif ftype == "XLSX":
        _generate_synthetic_xlsx(p, template)
    elif ftype == "TXT":
        _generate_synthetic_txt(p, template)
    else:
        raise ValueError(f"Unsupported decoy file type: {file_type}")

    logger.info(f"Generated synthetic {ftype} decoy: {p.name}")
    return p
